// CatalogKeys returns all keys defined in the Japanese catalog.
func CatalogKeys() []string {
	keys := make([]string, 0, len(catalog[JA]))
	for k := range catalog[JA] {
		keys = append(keys, k)
	}
	return keys
}

func Normalize(lang string) Lang {
	if strings.EqualFold(strings.TrimSpace(lang), string(EN)) || strings.HasPrefix(strings.ToLower(strings.TrimSpace(lang)), "en-") {
		return EN
	}
	return JA
}

func Translate(lang, key string, args ...any) string {
	l := Normalize(lang)
	value, ok := catalog[l][key]
	if !ok {
		value = catalog[JA][key]
	}
	if value == "" {
		value = key
	}
	if len(args) > 0 {
		return fmt.Sprintf(value, args...)
	}
	return value
}

// Has reports whether key is defined in the catalog (in Japanese, which every key has).
// Use it for stored values that may be either a catalog key or an older, already-written message.
func Has(key string) bool {
	_, ok := catalog[JA][key]
	return ok
}
